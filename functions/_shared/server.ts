/** Send one server-side event to PostHog, identified by the contact's email. */
export function captureForEmail(
	event: string,
	email: string,
	properties: Record<string, unknown>,
	request: Request,
): Promise<unknown> {
	const ua = request.headers.get('user-agent') ?? '';
	return fetch(CAPTURE_URL, {
		method: 'POST',
		headers: { 'content-type': 'application/json' },
		body: JSON.stringify({
			api_key: POSTHOG_TOKEN,
			event,
			distinct_id: email,
			timestamp: new Date().toISOString(),
			properties: {
				...properties,
				// The email client or Google's image proxy made this request, not the
				// visitor's browser, so don't let it set the person's location.
				$geoip_disable: true,
				$raw_user_agent: ua,
				$lib: 'shiftpatch-email-function',
			},
		}),
	}).catch(() => undefined);
}

export function normalizeEmail(raw: unknown): string | null {
	if (typeof raw !== 'string') return null;
	const email = raw.trim().toLowerCase();
	return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) && email.length <= 254 ? email : null;
}

/** HMAC-SHA256 as lowercase hex (matches Apps Script's computeHmacSha256Signature). */
export async function hmacHex(secret: string, message: string): Promise<string> {
	const key = await crypto.subtle.importKey(
		'raw',
		new TextEncoder().encode(secret),
		{ name: 'HMAC', hash: 'SHA-256' },
		false,
		['sign'],
	);
	const sig = await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(message));
	return [...new Uint8Array(sig)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

/** Constant-time compare of two hex strings. */
export function safeEqual(a: string, b: string): boolean {
	if (a.length !== b.length) return false;
	let diff = 0;
	for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
	return diff === 0;
}

/** Token for an email link: proves the link was generated by us for this email and action. */
export function linkToken(secret: string, email: string, action: string): Promise<string> {
	return hmacHex(secret, `${action}|${email}`);
}
